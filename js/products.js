/* Himalay — in-site product pages.
   products.html            → all categories (room filter + search)
   products.html?c=<cat>    → one category: every product, colour dots preview the photo
   products.html?p=<prod>   → one product: gallery, colour swatches, enquiry
   Data: js/catalog-data.js (generated by tools/build_catalog.py from the factory PNGs).
   Everything is built with createElement/textContent, and URL ids are only used
   after they've been matched against the data, so nothing from the URL reaches the DOM as HTML. */
(() => {
  const D = window.HIMALAY_CATALOG;
  const app = document.getElementById("app");
  if (!D || !app) return;

  const reduce = matchMedia("(prefers-reduced-motion: reduce)").matches;
  const WA = "919979011141";
  const catById = new Map(D.categories.map((c) => [c.id, c]));
  const prodById = new Map(D.products.map((p) => [p.id, p]));
  const prodsIn = (cid) => D.products.filter((p) => p.cat === cid);
  const colourCount = (cid) => prodsIn(cid).reduce((n, p) => n + p.variants.length, 0);

  /* tiny element helper: h("a.cls", {href}, child, "text", …) */
  const h = (tag, attrs, ...kids) => {
    const [name, ...cls] = tag.split(".");
    const el = document.createElement(name);
    if (cls.length) el.className = cls.join(" ");
    for (const [k, v] of Object.entries(attrs || {})) {
      if (v == null || v === false) continue;
      if (k === "style") for (const [sk, sv] of Object.entries(v)) el.style.setProperty(sk, sv);
      else if (k === "dataset") Object.assign(el.dataset, v);
      else if (k.startsWith("on")) el.addEventListener(k.slice(2), v);
      else el.setAttribute(k, v === true ? "" : v);
    }
    for (const kid of kids.flat()) if (kid != null && kid !== false) el.append(kid.nodeType ? kid : document.createTextNode(String(kid)));
    return el;
  };
  const img = (im, alt, opts = {}) => h("img", {
    src: opts.small ? im.sm : im.src, alt, width: im.w, height: im.h,
    loading: opts.eager ? "eager" : "lazy", decoding: "async",
  });
  const url = (q) => "products.html" + (q ? "?" + new URLSearchParams(q) : "");
  const crumbs = (...items) => h("nav.px-bc", { "aria-label": "Breadcrumb" },
    h("ol.px-crumbs", null, h("li", null, h("a", { href: "index.html" }, "Home")),
      items.map(([label, href]) => h("li", null, href ? h("a", { href }, label) : h("span", { "aria-current": "page" }, label)))));
  const setTitle = (t, desc) => {
    document.title = t + " – Himalay Thermoplast";
    if (desc) document.querySelector('meta[name="description"]')?.setAttribute("content", desc);
  };
  const plural = (n, one, many) => n + " " + (n === 1 ? one : many);

  /* ── product card, used by category view and "more in this range" ── */
  const card = (p, Hn = "h2") => {
    const first = p.variants[0];
    const photo = img(first.imgs[0], p.name + ", " + first.name, { small: true });
    const href = url({ p: p.id });
    const link = h("a", { href }, p.name);
    const show = (v, btn) => {
      photo.src = v.imgs[0].sm; photo.alt = p.name + ", " + v.name;
      link.href = url({ p: p.id, v: v.id });
      dots.querySelectorAll("button").forEach((b) => b.setAttribute("aria-pressed", String(b === btn)));
    };
    const MAX = 8;
    const dots = h("ul.px-dots", { "aria-label": "Colours" },
      p.variants.slice(0, MAX).map((v, i) => h("li", null, h("button", {
        type: "button", style: { "--sw": v.sw }, title: v.name, "aria-label": "Show " + v.name,
        "aria-pressed": String(i === 0),
        onmouseenter: (e) => show(v, e.currentTarget), onfocus: (e) => show(v, e.currentTarget), onclick: (e) => show(v, e.currentTarget),
      }))),
      p.variants.length > MAX ? h("li.px-dots__more", null, "+" + (p.variants.length - MAX)) : null);
    return h("article.px-card", null,
      h("div.px-card__ph", null, photo),
      h("div.px-card__body", null,
        p.code ? h("span.px-code", null, p.code) : null,
        h(Hn, null, link),
        p.short ? h("p.px-card__meta", null, p.short) : null,
        p.variants.length > 1 ? dots : h("p.px-card__meta", null, p.variants[0].name)));
  };

  /* ── view 1: all categories ── */
  const viewAll = () => {
    setTitle("All products", "Every Himalay Thermoplast range: bathroom sets, containers, jugs, dispensers, lunch boxes, mops and dustbins.");
    let room = "all";
    const tiles = D.categories.map((c) => {
      const n = prodsIn(c.id).length, k = colourCount(c.id);
      const hay = [c.name, c.keywords, ...prodsIn(c.id).flatMap((p) => [p.name, p.code])].join(" ").toLowerCase();
      const t = h("a.tile.rx-tile", { href: url({ c: c.id }), dataset: { g: c.room } },
        h("div.rx-tile__ph", null, img(c.cover, "", { small: true })),
        h("div.rx-tile__body", null, h("h2", { class: "px-tile-h" }, c.name),
          h("p.rx-tile__meta", null, plural(n, "product", "products") + " · " + plural(k, "colour", "colours")),
          h("span.rx-tile__go", { "aria-hidden": "true" }, "View")));
      t._hay = hay;
      return t;
    });
    const grid = h("div.rx-grid", null, tiles);
    const count = h("p.rx-count", { role: "status", "aria-live": "polite" });
    const empty = h("div.rx-empty", { hidden: true }, h("p", null, "Nothing matches that search."),
      h("button.rx-btn", { type: "button", onclick: () => { q.value = ""; setRoom("all"); q.focus(); } }, "Show all products"));
    const q = h("input", { type: "search", placeholder: "Search, e.g. bucket, jug, HT-01", autocomplete: "off", "aria-label": "Search products" });
    const apply = () => {
      const v = q.value.trim().toLowerCase();
      let n = 0;
      tiles.forEach((t) => { const hit = (room === "all" || t.dataset.g === room) && (!v || t._hay.includes(v)); t.hidden = !hit; if (hit) n++; });
      count.textContent = plural(n, "range", "ranges");
      empty.hidden = n > 0; grid.hidden = n === 0;
    };
    const chips = [{ id: "all", name: "All" }, ...D.rooms].map((r) => h("button.rx-chip", {
      type: "button", "aria-pressed": String(r.id === "all"), dataset: { f: r.id }, onclick: () => setRoom(r.id),
    }, r.name));
    const setRoom = (id) => { room = id; chips.forEach((c) => c.setAttribute("aria-pressed", String(c.dataset.f === id))); apply(); };
    q.addEventListener("input", apply);
    const totalP = D.products.length, totalV = D.products.reduce((n, p) => n + p.variants.length, 0);
    app.replaceChildren(h("section.rx.rx-cat.px", { "aria-labelledby": "h-px" }, h("div.c-wrap", null,
      crumbs(["All products"]),
      h("div.px-head", null,
        h("div", null, h("h1", { id: "h-px" }, "All products"),
          h("p.px-lead", null, "Every range we make in Morbi. Open one to see each product and all its colours.")),
        h("dl.px-head__stats", null,
          h("div", null, h("dt", null, "Ranges"), h("dd", null, D.categories.length)),
          h("div", null, h("dt", null, "Products"), h("dd", null, totalP)),
          h("div", null, h("dt", null, "Colours"), h("dd", null, totalV)))),
      h("div.rx-cat__bar", null, h("div.rx-chips", { role: "group", "aria-label": "Filter by room" }, chips),
        h("label.rx-search", null, svgSearch(), q)),
      count, grid, empty)));
    apply();
    const qs = new URLSearchParams(location.search).get("q");
    if (qs) { q.value = qs.slice(0, 60); apply(); }
  };
  const svgSearch = () => {
    const s = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    s.setAttribute("viewBox", "0 0 24 24"); s.setAttribute("aria-hidden", "true");
    const c = document.createElementNS(s.namespaceURI, "circle"); c.setAttribute("cx", "11"); c.setAttribute("cy", "11"); c.setAttribute("r", "7");
    const p = document.createElementNS(s.namespaceURI, "path"); p.setAttribute("d", "M20 20l-4-4");
    s.append(c, p); return s;
  };

  /* ── view 2: one category ── */
  const viewCat = (c) => {
    const ps = prodsIn(c.id);
    setTitle(c.name, c.blurb);
    const others = D.categories.filter((x) => x.id !== c.id);
    app.replaceChildren(h("section.rx.px", { "aria-labelledby": "h-px" }, h("div.c-wrap", null,
      crumbs(["All products", url()], [c.name]),
      h("div.px-head", null,
        h("div", null, h("h1", { id: "h-px" }, c.name), h("p.px-lead", null, c.blurb)),
        h("dl.px-head__stats", null,
          h("div", null, h("dt", null, "Products"), h("dd", null, ps.length)),
          h("div", null, h("dt", null, "Colours"), h("dd", null, colourCount(c.id))))),
      h("div.px-grid", null, ps.map((p) => card(p))),
      h("div.px-more", null, h("h2", null, "Other ranges"),
        h("ul.px-ranges", null, others.map((x) => h("li", null, h("a", { href: url({ c: x.id }) }, x.name))))))));
  };

  /* ── view 3: one product ── */
  const viewProd = (p, vid) => {
    const c = catById.get(p.cat);
    let v = p.variants.find((x) => x.id === vid) || p.variants[0];
    let shot = 0;
    setTitle(p.name + (p.code ? " (" + p.code + ")" : ""), p.blurb || c.blurb);

    const main = img(v.imgs[0], "", { eager: true });
    main.setAttribute("fetchpriority", "high");
    const label = h("b");
    const thumbs = h("ul.px-thumbs", { "aria-label": "Photos" });
    const enq = h("button.rx-btn", { type: "button" }, "Enquire about this product");
    const wa = h("a.rx-btn.px-wa", { target: "_blank", rel: "noopener" }, "Ask on WhatsApp");
    const enqText = () => [p.code, p.name, v.name].filter(Boolean).join(" – ");

    const setShot = (i) => {
      shot = i;
      const im = v.imgs[i];
      const swap = () => { main.src = im.src; main.width = im.w; main.height = im.h; main.alt = p.name + ", " + v.name; main.classList.remove("is-fading"); };
      if (reduce || main.src.endsWith(im.src)) swap(); else { main.classList.add("is-fading"); setTimeout(swap, 160); }
      thumbs.querySelectorAll("button").forEach((b, j) => b.setAttribute("aria-pressed", String(j === i)));
    };
    const renderThumbs = () => {
      // thumbnails = every colour's first photo + extra angles of the current colour
      thumbs.replaceChildren();
      v.imgs.forEach((im, i) => thumbs.append(h("li", null, h("button", {
        type: "button", "aria-label": v.name + ", photo " + (i + 1), "aria-pressed": String(i === shot), onclick: () => setShot(i),
      }, img(im, "", { small: true })))));
      thumbs.hidden = v.imgs.length < 2;
    };
    const setVariant = (nv, push) => {
      v = nv; shot = 0;
      label.textContent = v.name;
      swatches.querySelectorAll("button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.v === v.id)));
      enq.dataset.enq = enqText();
      wa.href = "https://wa.me/" + WA + "?text=" + encodeURIComponent("Hello Himalay, I'd like the dealer price for: " + enqText());
      renderThumbs(); setShot(0);
      if (push) history.replaceState(null, "", url({ p: p.id, v: v.id }));
    };
    const swatches = h("ul.px-swatches", { "aria-label": "Colours" }, p.variants.map((x) => h("li", null, h("button", {
      type: "button", style: { "--sw": x.sw }, dataset: { v: x.id }, "aria-pressed": "false", onclick: () => setVariant(x, true),
    }, x.name))));

    const facts = [["Range", c.name], ...(p.facts || [])];
    if (p.code) facts.unshift(["Code", p.code]);
    facts.push(["Colours", String(p.variants.length)]);
    const more = prodsIn(c.id).filter((x) => x.id !== p.id);

    app.replaceChildren(h("section.rx.px", { "aria-labelledby": "h-px" }, h("div.c-wrap", null,
      crumbs(["All products", url()], [c.name, url({ c: c.id })], [p.name]),
      h("div.px-prod", null,
        h("div.px-gal", null, h("div.px-gal__main", null, main), thumbs),
        h("div.px-info", null,
          p.code ? h("span.px-code", null, p.code) : null,
          h("h1", { id: "h-px" }, p.name),
          p.blurb ? h("p.px-lead", null, p.blurb) : null,
          h("div", null, h("p.px-label", null, p.variants.length > 1 ? "Colour" : "Finish", label), swatches),
          h("dl.px-facts", null, facts.map(([k, val]) => [h("dt", null, k), h("dd", null, val)])),
          h("div.px-acts", null, enq, wa),
          h("p.px-card__meta", null, "Dealers and distributors get factory prices. We reply within one working day."))),
      more.length ? h("div.px-more", null, h("h2", null, "More in " + c.name), h("div.px-grid", null, more.map((x) => card(x, "h3")))) : null)));
    setVariant(v, false);
  };

  const notFound = () => {
    setTitle("Product not found");
    app.replaceChildren(h("section.rx.px", null, h("div.c-wrap.px-missing", null,
      h("h1", null, "We couldn't find that product"),
      h("p.px-lead", null, "It may have moved. Browse every range instead."),
      h("a.rx-btn", { href: url() }, "See all products"))));
  };

  /* ── route ── */
  const qs = new URLSearchParams(location.search);
  const pid = qs.get("p"), cid = qs.get("c");
  if (pid) { const p = prodById.get(pid); p ? viewProd(p, qs.get("v")) : notFound(); }
  else if (cid) { const c = catById.get(cid); c ? viewCat(c) : notFound(); }
  else viewAll();
  if (location.hash === "") window.scrollTo(0, 0);
})();
